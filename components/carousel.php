<script>
(function () {
    var hero = document.querySelector('[data-collection]');
    if (!hero) return;

    var cards = Array.prototype.slice.call(hero.querySelectorAll('[data-card]'));
    var copies = Array.prototype.slice.call(hero.querySelectorAll('[data-copy]'));
    var backdrops = Array.prototype.slice.call(hero.querySelectorAll('[data-backdrop]'));
    var videos = Array.prototype.slice.call(hero.querySelectorAll('.collection-hero__video'));
    var cardVideos = Array.prototype.slice.call(hero.querySelectorAll('.collection-card__video'));
    var currentEl = hero.querySelector('[data-current]');
    var prevBtn = hero.querySelector('[data-prev]');
    var nextBtn = hero.querySelector('[data-next]');
    var stage = hero.querySelector('[data-stage]');
    var deck = hero.querySelector('#collectionDeck');
    var current = 0;
    var timer = null;

    var reduceMotion = window.matchMedia &&
        window.matchMedia('(prefers-reduced-motion: reduce)').matches;

    function syncVideos() {
        videos.forEach(function (video) {
            var backdrop = video.closest('[data-backdrop]');
            var index = backdrop ? parseInt(backdrop.getAttribute('data-backdrop'), 10) : -1;

            if (index === current && !reduceMotion) {
                if (!video.src && video.dataset.src) {
                    video.src = video.dataset.src;
                }

                video.classList.add('is-playing');
                var playPromise = video.play();

                if (playPromise && playPromise.catch) {
                    playPromise.catch(function () {
                        video.classList.remove('is-playing');
                    });
                }
            } else {
                video.pause();
                video.classList.remove('is-playing');
            }
        });
    }

    function syncCardVideos() {
        cardVideos.forEach(function (video) {
            var card = video.closest('[data-card]');
            var index = card ? parseInt(card.getAttribute('data-card'), 10) : -1;

            if (index === current && !reduceMotion) {
                if (!video.src && video.dataset.src) {
                    video.src = video.dataset.src;
                }

                video.classList.add('is-playing');
                var playPromise = video.play();

                if (playPromise && playPromise.catch) {
                    playPromise.catch(function () {
                        video.classList.remove('is-playing');
                    });
                }
            } else {
                video.pause();
                video.classList.remove('is-playing');
            }
        });
    }

    function layout() {
        cards.forEach(function (card, i) {
            var diff = i - current;
            var distance = Math.abs(diff);
            var direction = diff < 0 ? -1 : (diff > 0 ? 1 : 0);
            var visible = distance <= 2;

            card.style.setProperty('--x', (diff * 112) + 'px');
            card.style.setProperty('--y', Math.min(36, distance * 18).toFixed(1) + 'px');
            card.style.setProperty('--z', (-distance * 130) + 'px');
            card.style.setProperty('--rot', (direction * -17 * Math.min(distance, 2)) + 'deg');
            card.style.setProperty('--scale', (1 - Math.min(distance, 2) * 0.09).toFixed(3));
            card.style.setProperty('--opacity', visible ? (distance === 0 ? '1' : '0.55') : '0');
            card.style.setProperty('--blur', (distance === 0 ? 0 : Math.min(2.6, distance * 1.1)).toFixed(2) + 'px');
            card.style.pointerEvents = visible ? 'auto' : 'none';
            card.classList.toggle('is-active', distance === 0);
        });

        copies.forEach(function (copy, i) {
            var active = i === current;
            copy.classList.toggle('is-active', active);
            copy.setAttribute('aria-hidden', active ? 'false' : 'true');
        });

        backdrops.forEach(function (backdrop, i) {
            backdrop.classList.toggle('is-active', i === current);
        });

        syncVideos();
        syncCardVideos();

        if (currentEl) {
            currentEl.textContent = String(current + 1).padStart(2, '0');
        }
    }

    function show(index) {
        if (!cards.length) return;
        current = (index + cards.length) % cards.length;
        layout();
    }

    function next() { show(current + 1); }
    function prev() { show(current - 1); }

    function startAutoplay() {
        if (reduceMotion) return;
        clearInterval(timer);
        timer = setInterval(next, 7000);
    }

    if (nextBtn) nextBtn.addEventListener('click', function () { next(); startAutoplay(); });
    if (prevBtn) prevBtn.addEventListener('click', function () { prev(); startAutoplay(); });

    cards.forEach(function (card, i) {
        card.addEventListener('click', function () {
            if (i === current) return;
            show(i);
            startAutoplay();
        });
    });

    hero.addEventListener('mouseenter', function () { clearInterval(timer); });
    hero.addEventListener('mouseleave', startAutoplay);

    hero.setAttribute('tabindex', '0');
    hero.addEventListener('keydown', function (event) {
        if (event.key === 'ArrowRight') { next(); startAutoplay(); }
        if (event.key === 'ArrowLeft') { prev(); startAutoplay(); }
    });

    /* Arrastre 3D */
    var drag = { active: false, moved: false, startX: 0 };

    if (stage) {
        stage.addEventListener('pointerdown', function (event) {
            if (event.pointerType === 'mouse' && event.button !== 0) return;
            drag.active = true;
            drag.moved = false;
            drag.startX = event.clientX;
            clearInterval(timer);
        });

        stage.addEventListener('pointermove', function (event) {
            if (!drag.active) return;
            var dx = event.clientX - drag.startX;
            if (!drag.moved && Math.abs(dx) > 6) {
                drag.moved = true;
                try { stage.setPointerCapture(event.pointerId); } catch (error) {}
            }
            if (drag.moved && deck) deck.style.transform = 'translateX(' + (dx * 0.12) + 'px)';
        });

        function endDrag(event) {
            if (!drag.active) return;
            drag.active = false;
            if (deck) deck.style.transform = '';

            try { stage.releasePointerCapture(event.pointerId); } catch (error) {}

            if (drag.moved) {
                var dx = event.clientX - drag.startX;
                if (dx < -50) next();
                else if (dx > 50) prev();
            }

            startAutoplay();
        }

        stage.addEventListener('pointerup', endDrag);
        stage.addEventListener('pointercancel', endDrag);

        stage.addEventListener('click', function (event) {
            if (!drag.moved) return;
            event.preventDefault();
            event.stopPropagation();
            drag.moved = false;
        }, true);
    }

    var touchStartX = 0;
    hero.addEventListener('touchstart', function (event) {
        if (event.target.closest('[data-stage]')) return;
        touchStartX = event.changedTouches[0].clientX;
        clearInterval(timer);
    }, { passive: true });

    hero.addEventListener('touchend', function (event) {
        if (event.target.closest('[data-stage]')) return;
        var dx = event.changedTouches[0].clientX - touchStartX;
        if (Math.abs(dx) > 45) {
            if (dx < 0) next(); else prev();
        }
        startAutoplay();
    }, { passive: true });

    /* Video interactivo solo para Bachillerato */
    var featuredVideo = hero.querySelector('.collection-card[data-card="0"] .collection-card__video');
    var featuredToggle = hero.querySelector('[data-video-toggle]');
    var featuredProgress = hero.querySelector('[data-video-progress]');

    function setToggleState(paused) {
        if (!featuredToggle) return;
        var icon = featuredToggle.querySelector('i');
        if (icon) {
            icon.className = paused ? 'bx bx-play' : 'bx bx-pause';
        }
        featuredToggle.setAttribute('aria-label', paused ? 'Reproducir video' : 'Pausar video');
    }

    if (featuredVideo && featuredToggle) {
        featuredToggle.addEventListener('click', function (event) {
            event.preventDefault();
            event.stopPropagation();

            if (featuredVideo.paused) {
                var promise = featuredVideo.play();
                if (promise && promise.catch) {
                    promise.catch(function () {});
                }
            } else {
                featuredVideo.pause();
            }
        });

        featuredVideo.addEventListener('play', function () { setToggleState(false); });
        featuredVideo.addEventListener('pause', function () { setToggleState(true); });
        featuredVideo.addEventListener('timeupdate', function () {
            if (featuredProgress && featuredVideo.duration) {
                featuredProgress.style.width = (featuredVideo.currentTime / featuredVideo.duration * 100) + '%';
            }
        });
    }

    layout();
    startAutoplay();
})();
</script>
